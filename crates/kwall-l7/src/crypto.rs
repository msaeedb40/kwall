/// Calculates the Shannon entropy of a string (in bits per symbol).
#[must_use]
pub fn shannon_entropy(data: &str) -> f64 {
    shannon_entropy_bytes(data.as_bytes())
}

/// Calculates the Shannon entropy of raw byte data.
#[must_use]
pub fn shannon_entropy_bytes(data: &[u8]) -> f64 {
    if data.is_empty() {
        return 0.0;
    }

    let mut counts = [0usize; 256];
    for &byte in data {
        counts[byte as usize] += 1;
    }

    let len_f = data.len() as f64;
    let mut entropy = 0.0f64;

    for &count in &counts {
        if count > 0 {
            let p = count as f64 / len_f;
            entropy -= p * p.log2();
        }
    }

    entropy
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_md5_vectors() {
        // RFC 1321 test vectors
        assert_eq!(md5_hex(b""), "d41d8cd98f00b204e9800998ecf8427e");
        assert_eq!(md5_hex(b"a"), "0cc175b9c0f1b6a831c399e269772661");
        assert_eq!(md5_hex(b"abc"), "900150983cd24fb0d6963f7d28e17f72");
        assert_eq!(
            md5_hex(b"message digest"),
            "f96b697d7cb7938d525a2f31aaf161d0"
        );
    }

    #[test]
    fn test_sha256_vectors() {
        // FIPS 180-4 test vectors
        assert_eq!(
            sha256_hex(b""),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        assert_eq!(
            sha256_hex(b"abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
    }

    #[test]
    fn test_shannon_entropy() {
        // Low entropy string (repeated single character)
        assert_eq!(shannon_entropy("aaaaaaa"), 0.0);
        // Moderate entropy
        let ent = shannon_entropy("abcdefgh");
        assert!((ent - 3.0).abs() < 1e-4);
        // High entropy (simulated base64 payload)
        let high_ent = shannon_entropy("aX9zK2Lp0QmNdF8wVhJ7");
        assert!(high_ent > 3.8);
    }
}
